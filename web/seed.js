// #88：种子在表单里始终按**字符串**传，别走 Number()。
//
// ComfyUI 的种子是 i64，老图里有 1918999279702401148 这种超过 2^53 的值；JS 的
// Number 会把它舍入成另一个数（…148 → …000），拿它再生成就是另一张图。后端两种都收
// （数字或整数字符串），所以这里能原样回传就原样回传。

function seedArg() {
  const t = String($("seed") ? $("seed").value : "").trim();
  return /^-?\d+$/.test(t) ? t : -1;
}
